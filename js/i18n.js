function detect() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (LANGS.includes(saved)) return saved;
  } catch {
    /* storage bloqueado */
  }
  return (navigator.language || '').toLowerCase().startsWith('pt') ? 'pt' : 'en';
}

let current = detect();

export const getLang = () => current;
export const htmlLang = () => HTML_LANG[current];

export function setLang(lang) {
  current = LANGS.includes(lang) ? lang : 'pt';
  try {
    localStorage.setItem(STORAGE_KEY, current);
  } catch {
    /* storage bloqueado */
  }
}

export function t(key, vars) {
  const str = STRINGS[current][key] ?? STRINGS.pt[key] ?? key;
  return vars ? str.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m)) : str;
}

export function ordinal(n) {
  if (current === 'pt') return `${n}º`;
  const rem100 = n % 100;
  const suffix = rem100 >= 11 && rem100 <= 13 ? 'th' : ({ 1: 'st', 2: 'nd', 3: 'rd' }[n % 10] ?? 'th');
  return `${n}${suffix}`;
}
